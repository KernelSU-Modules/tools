// Bundle the action into a single self-contained dist/index.js (committed; Actions cannot install deps).
//
//   node scripts/build.mjs           write dist/index.js
//   node scripts/build.mjs --check   rebuild into a temp dir and exit 1 if dist/index.js differs (for CI)
import { build } from 'esbuild';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const committed = join(root, 'dist', 'index.js');
const tmp = check ? mkdtempSync(join(tmpdir(), 'kernelsu-module-release-')) : null;
const outfile = tmp ? join(tmp, 'index.js') : committed;

try {
  await build({
    absWorkingDir: root,
    entryPoints: ['src/index.ts'],
    outfile,
    bundle: true,
    platform: 'node',
    target: 'node22',
    format: 'esm',
    minify: false,
    legalComments: 'none',
    banner: {
      js: "// Generated by scripts/build.mjs from src/ — do not edit.\nimport { createRequire as __ksuCreateRequire } from 'node:module';\nconst require = __ksuCreateRequire(import.meta.url);",
    },
    logLevel: check ? 'warning' : 'info',
  });

  if (check) {
    const fresh = readFileSync(outfile, 'utf8');
    const current = existsSync(committed) ? readFileSync(committed, 'utf8') : null;
    if (current !== fresh) {
      console.error(
        `dist/index.js is ${current === null ? 'missing' : 'out of date'}: run \`pnpm --filter @kernelsu-modules/module-release build\` and commit the result.`,
      );
      process.exitCode = 1;
    } else console.log('dist/index.js is up to date.');
  }
} finally {
  if (tmp) rmSync(tmp, { recursive: true, force: true });
}
