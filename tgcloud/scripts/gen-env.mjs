#!/usr/bin/env node
// Generates tgcloud/lib/env.js (git-ignored) from environment variables right before `tgcloud push`.
// Telegram Serverless has no documented secrets mechanism, so the forward secret is baked into the
// deployed module. Only holders of the tgcloud CLI token (BotFather → Serverless → CLI Access) can read it back.
//
//   TG_FORWARD_SECRET=... [PORTAL_URL=https://developers.kernelsu.org] node scripts/gen-env.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const secret = process.env.TG_FORWARD_SECRET ?? '';
const portal = process.env.PORTAL_URL || 'https://developers.kernelsu.org';
if (secret.length < 32 || /\s/.test(secret)) {
  console.error('TG_FORWARD_SECRET must be set (>= 32 chars, no whitespace). Generate one with: openssl rand -hex 32');
  process.exit(1);
}
if (!/^https:\/\/[A-Za-z0-9.-]+(:\d+)?$/.test(portal)) {
  console.error(`PORTAL_URL must be an https origin without a path, got "${portal}"`);
  process.exit(1);
}
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'tgcloud', 'lib', 'env.js');
writeFileSync(
  out,
  '// GENERATED by scripts/gen-env.mjs at deploy time. DO NOT COMMIT (git-ignored).\n' +
    `export const FORWARD_SECRET = ${JSON.stringify(secret)};\n` +
    `export const PORTAL_URL = ${JSON.stringify(portal)};\n`,
  { mode: 0o600 },
);
console.log(`wrote ${out} (PORTAL_URL=${portal})`);
