#!/usr/bin/env node
// Generates src/styles/markdown-theme.css from github-markdown-css: the declarations of the dark stylesheet that
// differ from the light one (global.css imports github-markdown-light.css as the base), scoped with :where() (no
// added specificity, so later rules in global.css still win) to the site's theme selectors (prefers-color-scheme
// unless <html data-theme="light">, or <html data-theme="dark">). Lets the theme toggle switch README styling
// without inline styles or scripts. Re-run after upgrading github-markdown-css:
//   node site/scripts/gen-markdown-theme.mjs          (writes)
//   node site/scripts/gen-markdown-theme.mjs --check  (exit 1 when out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = require.resolve('github-markdown-css/package.json').replace(/package\.json$/, '');
const version = JSON.parse(readFileSync(`${pkgDir}package.json`, 'utf8')).version;
const OUT = fileURLToPath(new URL('../src/styles/markdown-theme.css', import.meta.url));

/** Split a declaration block on ";" outside quotes and parentheses. */
function splitDecls(body) {
  const out = [];
  let cur = '';
  let quote = null;
  let depth = 0;
  for (const ch of body) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'") quote = ch;
    else if (ch === '(') depth++;
    else if (ch === ')') depth--;
    else if (ch === ';' && depth === 0) {
      out.push(cur);
      cur = '';
      continue;
    }
    cur += ch;
  }
  out.push(cur);
  return out;
}

/** Flat stylesheet (no at-rules) -> [{selector, decls: [[prop, value]]}]. */
function parse(css) {
  const rules = [];
  const src = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const re = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = re.exec(src))) {
    const selector = m[1].trim().replace(/\s+/g, ' ');
    if (selector.startsWith('@')) throw new Error(`unexpected at-rule: ${selector}`);
    const decls = splitDecls(m[2])
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => {
        const i = d.indexOf(':');
        return [d.slice(0, i).trim(), d.slice(i + 1).trim()];
      });
    rules.push({ selector, decls });
  }
  return rules;
}

const light = parse(readFileSync(`${pkgDir}github-markdown-light.css`, 'utf8'));
const dark = parse(readFileSync(`${pkgDir}github-markdown-dark.css`, 'utf8'));
if (light.length !== dark.length) throw new Error('light/dark stylesheets differ in structure');

const block = (sel, decls, indent = '') =>
  `${indent}${sel} {\n${decls.map(([p, v]) => `${indent}  ${p}: ${v};`).join('\n')}\n${indent}}\n`;
const scope = (prefix, selector) =>
  selector
    .split(',')
    .map((s) => `${prefix} ${s.trim()}`)
    .join(',\n');

const overrides = [];
for (let i = 0; i < light.length; i++) {
  const l = light[i];
  const d = dark[i];
  if (l.selector !== d.selector) throw new Error(`rule ${i}: selector mismatch ${l.selector} / ${d.selector}`);
  const lv = new Map(l.decls);
  const diff = d.decls.filter(([p, v]) => lv.get(p) !== v);
  if (diff.length) overrides.push({ selector: l.selector, decls: diff });
}

let out = `/* GENERATED by site/scripts/gen-markdown-theme.mjs from github-markdown-css ${version}; do not edit.\n   Dark overrides on top of github-markdown-light.css. */\n`;
out += '\n/* Dark: system preference unless forced light. */\n@media (prefers-color-scheme: dark) {\n';
for (const o of overrides) out += block(scope(':where(:root:not([data-theme="light"]))', o.selector).replace(/\n/g, '\n  '), o.decls, '  ');
out += '}\n\n/* Dark: forced. */\n';
for (const o of overrides) out += block(scope(':where(:root[data-theme="dark"])', o.selector), o.decls);

if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(OUT, 'utf8');
  } catch {}
  if (cur !== out) {
    console.error('src/styles/markdown-theme.css is out of date: run node site/scripts/gen-markdown-theme.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT} (${overrides.length} dark overrides)`);
}
